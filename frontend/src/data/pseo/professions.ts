function toSlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function genericLineItems(name: string, low: number, high: number): ProfessionLineItem[] {
  const mid = Math.round((low + high) / 2);
  return [
    { description: `${name} hourly rate`, unit: "hr", rate: mid },
    { description: `${name} project / package`, unit: "flat", rate: mid * 10 },
    { description: "Materials or supplies", unit: "flat", rate: 0 },
    { description: "Rush turnaround fee", unit: "flat", rate: Math.round(mid * 0.5 / 10) * 10 },
  ];
}

